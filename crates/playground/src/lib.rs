//! The matching core in a browser. Compiled to WebAssembly, the same `OrderBook` the exchange
//! runs replays the benchmark's order flow, so a visitor can measure it on their own machine,
//! and a live book that a participant-like flow keeps busy, for the page to draw.
//!
//! The module exports plain functions of numbers, so the page needs no glue code:
//!
//! - the benchmark: [`prepare`] records the flow once; then, round after round,
//!   [`warm_up`] replays its first part into a fresh book, untimed, and [`measure`] replays
//!   the rest, which the page times; [`digest_low`] and [`digest_high`] give the book's
//!   state digest afterwards, which the page compares with [`EXPECTED_DIGEST`], the one
//!   every native build gets;
//! - the live book: [`live_step`] applies more of an endless flow, and fills the buffer at
//!   [`live_depth`] with the best levels of each side.
//!
//! Every function runs on the page's one thread; the state lives in a thread-local.

use std::cell::RefCell;

use orderbook::workload::{Workload, WorkloadConfig};
use orderbook::{Command, Event, OrderBook, Side};

/// Commands replayed into a fresh book before each measured round: enough to reach the
/// benchmark's steady state, about six thousand resting orders.
pub const WARM_UP: u32 = 200_000;

/// Commands in each measured round.
pub const MEASURED: u32 = 500_000;

/// The book's digest after the warm-up and one measured round of the benchmark's flow:
/// the same on every platform, which the page checks the browser's against.
pub const EXPECTED_DIGEST: u64 = 0x66ea_3363_2fec_1c5a;

/// Levels of each side the live book reports.
pub const LIVE_LEVELS: usize = 12;

/// Numbers per level in the live buffer: price, quantity, orders.
const FIELDS: usize = 3;

thread_local! {
    static BENCH: RefCell<Option<Bench>> = const { RefCell::new(None) };
    static LIVE: RefCell<Option<Live>> = const { RefCell::new(None) };
}

/// The benchmark's flow, recorded, and the book it is replayed into.
struct Bench {
    commands: Vec<Command>,
    book: OrderBook,
    events: Vec<Event>,
}

/// The live book, the flow that keeps it busy, and what the page reads of it.
struct Live {
    book: OrderBook,
    workload: Workload,
    events: Vec<Event>,
    commands: u64,
    trades: u64,
    last_price: i64,
    /// Bids best first, then asks best first: [`LIVE_LEVELS`] of each, [`FIELDS`] numbers
    /// a level, zeros where a side has fewer levels.
    depth: Vec<f64>,
}

/// The benchmark's flow, as the native latency and throughput benchmarks generate it.
fn flow() -> WorkloadConfig {
    WorkloadConfig::default()
}

/// Records the benchmark's flow: [`WARM_UP`] commands and then [`MEASURED`], generated by
/// participants who see every event, as in the native benchmark. Returns how many.
#[unsafe(no_mangle)]
pub extern "C" fn prepare() -> u32 {
    let cfg = flow();
    let mut book = OrderBook::new(cfg.book_config());
    let mut workload = Workload::new(cfg);
    let total = (WARM_UP + MEASURED) as usize;
    let mut commands = Vec::with_capacity(total);
    let mut events = Vec::with_capacity(4_096);
    for _ in 0..total {
        let command = workload.next_command();
        events.clear();
        book.process(command, &mut events);
        events.iter().for_each(|event| workload.observe(event));
        commands.push(command);
    }
    let bench = Bench {
        commands,
        book: OrderBook::new(cfg.book_config()),
        events,
    };
    BENCH.with(|cell| *cell.borrow_mut() = Some(bench));
    total as u32
}

/// Starts a round: a fresh book, with the warm-up replayed into it.
#[unsafe(no_mangle)]
pub extern "C" fn warm_up() {
    BENCH.with(|cell| {
        let mut cell = cell.borrow_mut();
        let bench = cell.as_mut().expect("prepare first");
        bench.book = OrderBook::new(flow().book_config());
        let Bench {
            commands,
            book,
            events,
        } = bench;
        replay(book, &commands[..WARM_UP as usize], events);
    });
}

/// Replays the measured commands: what the page times. Returns how many.
#[unsafe(no_mangle)]
pub extern "C" fn measure() -> u32 {
    BENCH.with(|cell| {
        let mut cell = cell.borrow_mut();
        let bench = cell.as_mut().expect("prepare first");
        let Bench {
            commands,
            book,
            events,
        } = bench;
        replay(book, &commands[WARM_UP as usize..], events);
        MEASURED
    })
}

/// The low 32 bits of the benchmark book's digest.
#[unsafe(no_mangle)]
pub extern "C" fn digest_low() -> u32 {
    digest() as u32
}

/// The high 32 bits of the benchmark book's digest.
#[unsafe(no_mangle)]
pub extern "C" fn digest_high() -> u32 {
    (digest() >> 32) as u32
}

/// The low 32 bits of the digest every native build gets.
#[unsafe(no_mangle)]
pub extern "C" fn expected_low() -> u32 {
    EXPECTED_DIGEST as u32
}

/// The high 32 bits of the digest every native build gets.
#[unsafe(no_mangle)]
pub extern "C" fn expected_high() -> u32 {
    (EXPECTED_DIGEST >> 32) as u32
}

/// Resting orders on the benchmark's book.
#[unsafe(no_mangle)]
pub extern "C" fn resting_orders() -> u32 {
    BENCH.with(|cell| {
        cell.borrow()
            .as_ref()
            .map_or(0, |bench| bench.book.order_count() as u32)
    })
}

fn digest() -> u64 {
    BENCH.with(|cell| {
        cell.borrow()
            .as_ref()
            .map_or(0, |bench| bench.book.digest())
    })
}

/// Applies `commands` to `book`, as the native benchmark does: each command's events
/// collected, then dropped.
fn replay(book: &mut OrderBook, commands: &[Command], events: &mut Vec<Event>) {
    for &command in commands {
        events.clear();
        book.process(command, events);
    }
}

/// Applies `n` more commands of the live flow, a slower and calmer market than the
/// benchmark's, and refreshes the depth the page reads. Returns the commands applied so far.
#[unsafe(no_mangle)]
pub extern "C" fn live_step(n: u32) -> u32 {
    LIVE.with(|cell| {
        let mut cell = cell.borrow_mut();
        let live = cell.get_or_insert_with(|| {
            let cfg = WorkloadConfig {
                seed: 0x0B00_C0DE,
                max_live: 600,
                passive_depth: 12,
                max_qty: 40,
                ..WorkloadConfig::default()
            };
            Live {
                book: OrderBook::new(cfg.book_config()),
                workload: Workload::new(cfg),
                events: Vec::with_capacity(1_024),
                commands: 0,
                trades: 0,
                last_price: 0,
                depth: vec![0.0; 2 * LIVE_LEVELS * FIELDS],
            }
        });
        for _ in 0..n {
            let command = live.workload.next_command();
            live.events.clear();
            live.book.process(command, &mut live.events);
            for event in &live.events {
                live.workload.observe(event);
                if let Event::Trade { price, .. } = *event {
                    live.trades += 1;
                    live.last_price = price;
                }
            }
            live.commands += 1;
        }
        live.depth.fill(0.0);
        for (half, side) in [Side::Buy, Side::Sell].into_iter().enumerate() {
            let levels = live.book.depth(side).take(LIVE_LEVELS);
            for (index, level) in levels.enumerate() {
                let at = (half * LIVE_LEVELS + index) * FIELDS;
                live.depth[at] = level.price as f64;
                live.depth[at + 1] = level.qty as f64;
                live.depth[at + 2] = f64::from(level.orders);
            }
        }
        live.commands as u32
    })
}

/// Where the live depth is, in the module's memory: `2 × LIVE_LEVELS × 3` numbers.
#[unsafe(no_mangle)]
pub extern "C" fn live_depth() -> usize {
    LIVE.with(|cell| {
        cell.borrow()
            .as_ref()
            .map_or(0, |live| live.depth.as_ptr() as usize)
    })
}

/// Trades on the live book so far.
#[unsafe(no_mangle)]
pub extern "C" fn live_trades() -> u32 {
    LIVE.with(|cell| cell.borrow().as_ref().map_or(0, |live| live.trades as u32))
}

/// The live book's last trade price, or zero before its first trade.
#[unsafe(no_mangle)]
pub extern "C" fn live_last_price() -> f64 {
    LIVE.with(|cell| {
        cell.borrow()
            .as_ref()
            .map_or(0.0, |live| live.last_price as f64)
    })
}

/// Resting orders on the live book.
#[unsafe(no_mangle)]
pub extern "C" fn live_orders() -> u32 {
    LIVE.with(|cell| {
        cell.borrow()
            .as_ref()
            .map_or(0, |live| live.book.order_count() as u32)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The digest the page expects is the one a native build gets, and two rounds of the
    /// benchmark end in the same state.
    #[test]
    fn the_browser_is_held_to_the_native_digest() {
        assert_eq!(prepare(), WARM_UP + MEASURED);
        warm_up();
        assert_eq!(measure(), MEASURED);
        let first = digest();
        assert_eq!(first, EXPECTED_DIGEST, "{first:#018x}");
        warm_up();
        measure();
        assert_eq!(digest(), first);
        assert_eq!(
            u64::from(digest_high()) << 32 | u64::from(digest_low()),
            u64::from(expected_high()) << 32 | u64::from(expected_low())
        );
        assert!(resting_orders() > 1_000, "{}", resting_orders());
    }

    /// The live book trades, and reports its best levels, best first, bids below asks.
    #[test]
    fn the_live_book_trades_and_shows_its_levels() {
        let applied = live_step(5_000);
        assert_eq!(applied, 5_000);
        assert!(live_trades() > 0);
        assert!(live_orders() > 0);
        assert!(live_last_price() > 0.0);
        LIVE.with(|cell| {
            let cell = cell.borrow();
            let depth = &cell.as_ref().unwrap().depth;
            let (bids, asks) = depth.split_at(LIVE_LEVELS * FIELDS);
            assert!(bids[0] > 0.0 && asks[0] > 0.0);
            assert!(bids[0] < asks[0], "the best bid is below the best ask");
            assert!(bids[FIELDS] < bids[0] && asks[FIELDS] > asks[0]);
        });
        assert_ne!(live_depth(), 0);
    }
}
